CREATE FUNCTION public.article_name_initials(p_name text) RETURNS text
    LANGUAGE sql IMMUTABLE
    AS $$
    SELECT COALESCE(string_agg(upper(left(word, 1)), ''), '')
    FROM unnest(regexp_split_to_array(trim(p_name), '\s+')) AS word
    WHERE word <> '';
$$;


