-- Paiement automatique Mobile Money : statut hors file agence, frais, grilles de retrait.

ALTER TABLE public.customer_mobile_money_submission
    DROP CONSTRAINT IF EXISTS customer_mobile_money_submission_status_check;

ALTER TABLE public.customer_mobile_money_submission
    ADD CONSTRAINT customer_mobile_money_submission_status_check
        CHECK (status IN ('INITIE', 'VALIDE', 'REJETE', 'EN_COURS', 'ECHEC'));

ALTER TABLE public.customer_mobile_money_submission
    ADD COLUMN IF NOT EXISTS channel character varying(20) NOT NULL DEFAULT 'MANUAL',
    ADD COLUMN IF NOT EXISTS network character varying(10),
    ADD COLUMN IF NOT EXISTS withdrawal_fee double precision,
    ADD COLUMN IF NOT EXISTS gateway_fee_rate double precision,
    ADD COLUMN IF NOT EXISTS gateway_fee double precision,
    ADD COLUMN IF NOT EXISTS amount_charged double precision,
    ADD COLUMN IF NOT EXISTS paygate_payment_id character varying(40);

CREATE UNIQUE INDEX IF NOT EXISTS uk_cmm_paygate_payment
    ON public.customer_mobile_money_submission (paygate_payment_id)
    WHERE paygate_payment_id IS NOT NULL;

ALTER TABLE public.customer_tontine_mm_submission
    DROP CONSTRAINT IF EXISTS customer_tontine_mm_submission_status_check;

ALTER TABLE public.customer_tontine_mm_submission
    ADD CONSTRAINT customer_tontine_mm_submission_status_check
        CHECK (status IN ('INITIE', 'VALIDE', 'REJETE', 'EN_COURS', 'ECHEC'));

ALTER TABLE public.customer_tontine_mm_submission
    ADD COLUMN IF NOT EXISTS channel character varying(20) NOT NULL DEFAULT 'MANUAL',
    ADD COLUMN IF NOT EXISTS network character varying(10),
    ADD COLUMN IF NOT EXISTS withdrawal_fee double precision,
    ADD COLUMN IF NOT EXISTS gateway_fee_rate double precision,
    ADD COLUMN IF NOT EXISTS gateway_fee double precision,
    ADD COLUMN IF NOT EXISTS amount_charged double precision,
    ADD COLUMN IF NOT EXISTS paygate_payment_id character varying(40);

CREATE UNIQUE INDEX IF NOT EXISTS uk_ctmm_paygate_payment
    ON public.customer_tontine_mm_submission (paygate_payment_id)
    WHERE paygate_payment_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.mobile_money_withdrawal_fee_bracket (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL,
    network character varying(10) NOT NULL,
    min_amount bigint NOT NULL,
    max_amount bigint NOT NULL,
    fee_amount bigint NOT NULL,
    CONSTRAINT mobile_money_withdrawal_fee_bracket_visibility_check CHECK (
        visibility IN ('ENABLED', 'DISABLED', 'DELETED')
    ),
    CONSTRAINT mobile_money_withdrawal_fee_bracket_network_check CHECK (
        network IN ('MIXX', 'FLOOZ')
    ),
    CONSTRAINT mobile_money_withdrawal_fee_bracket_range_check CHECK (
        min_amount >= 0 AND min_amount < max_amount AND fee_amount >= 0
    )
);

CREATE INDEX IF NOT EXISTS idx_mm_withdrawal_fee_network
    ON public.mobile_money_withdrawal_fee_bracket (network, visibility);
