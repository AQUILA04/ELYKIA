INSERT INTO public.client_adhesion (
    reg_user_id, date_reg, visibility,
    client_id, adhesion_type, status, adhesion_fee, fee_waived, balance,
    activated_at, activated_by, source
)
SELECT DISTINCT ON (a.client_id)
    'migration',
    NOW(),
    'ENABLED',
    a.client_id,
    'PERSONAL',
    'ACTIVE',
    0,
    TRUE,
    COALESCE(a.account_balance, 0),
    NOW(),
    'migration',
    'MIGRATION'
FROM public.account a
WHERE a.client_id IS NOT NULL
  AND (a.visibility IS NULL OR a.visibility <> 'DELETED')
  AND NOT EXISTS (
      SELECT 1 FROM public.client_adhesion ca
      WHERE ca.client_id = a.client_id
        AND ca.adhesion_type = 'PERSONAL'
        AND ca.visibility = 'ENABLED'
        AND ca.status IN ('PENDING', 'ACTIVE', 'SUSPENDED')
  )
ORDER BY a.client_id, a.id;

INSERT INTO public.adhesion_balance_movement (
    reg_user_id, date_reg, visibility,
    client_adhesion_id, amount, movement_type, note
)
SELECT
    'migration',
    NOW(),
    'ENABLED',
    ca.id,
    ca.balance,
    'MIGRATION',
    'Reprise du solde de compte vers l''adhésion personnelle'
FROM public.client_adhesion ca
WHERE ca.source = 'MIGRATION'
  AND NOT EXISTS (
      SELECT 1 FROM public.adhesion_balance_movement m
      WHERE m.client_adhesion_id = ca.id AND m.movement_type = 'MIGRATION'
  );
