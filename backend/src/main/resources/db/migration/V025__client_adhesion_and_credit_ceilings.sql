-- Adhésions PERSONAL / BUSINESS / EVENT : soldes séparés, plafonds par type.
-- Les comptes existants deviennent une adhésion personnelle (solde repris, plafond fixe ensuite).
-- Clients dont l'ancien plafond (solde x 6) dépasse 35 000 FCFA, à traiter avant bascule métier :
-- SELECT c.id, c.firstname, c.lastname, a.account_balance, a.account_balance * 6 AS ancien_plafond
-- FROM account a JOIN client c ON c.id = a.client_id
-- WHERE a.account_balance * 6 > 35000;

CREATE TABLE IF NOT EXISTS public.client_adhesion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL DEFAULT 'ENABLED',
    client_id bigint NOT NULL,
    adhesion_type character varying(20) NOT NULL,
    status character varying(20) NOT NULL,
    adhesion_fee double precision NOT NULL DEFAULT 0,
    fee_waived boolean NOT NULL DEFAULT false,
    balance double precision NOT NULL DEFAULT 0,
    activated_at timestamp(6) without time zone,
    activated_by character varying(255),
    closed_at timestamp(6) without time zone,
    source character varying(30) NOT NULL,
    CONSTRAINT client_adhesion_type_check CHECK (adhesion_type IN ('PERSONAL', 'BUSINESS', 'EVENT')),
    CONSTRAINT client_adhesion_status_check CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'CLOSED')),
    CONSTRAINT client_adhesion_source_check CHECK (source IN ('MIGRATION', 'COUNTER', 'CUSTOMER_SPACE', 'BUSINESS_UNLOCK')),
    CONSTRAINT fk_client_adhesion_client FOREIGN KEY (client_id) REFERENCES public.client(id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_client_adhesion_open
    ON public.client_adhesion (client_id, adhesion_type)
    WHERE status IN ('PENDING', 'ACTIVE', 'SUSPENDED') AND visibility = 'ENABLED';

CREATE INDEX IF NOT EXISTS idx_client_adhesion_client
    ON public.client_adhesion (client_id);

CREATE TABLE IF NOT EXISTS public.adhesion_balance_movement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL DEFAULT 'ENABLED',
    client_adhesion_id bigint NOT NULL,
    amount double precision NOT NULL,
    movement_type character varying(30) NOT NULL,
    note character varying(500),
    CONSTRAINT adhesion_movement_type_check CHECK (movement_type IN ('ADHESION_FEE', 'TOP_UP', 'ADJUSTMENT', 'MIGRATION', 'OPENING')),
    CONSTRAINT fk_adhesion_movement_adhesion FOREIGN KEY (client_adhesion_id) REFERENCES public.client_adhesion(id)
);

CREATE INDEX IF NOT EXISTS idx_adhesion_movement_adhesion
    ON public.adhesion_balance_movement (client_adhesion_id);

CREATE TABLE IF NOT EXISTS public.customer_adhesion_submission (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL DEFAULT 'ENABLED',
    client_id bigint NOT NULL,
    adhesion_type character varying(20) NOT NULL,
    request_kind character varying(20) NOT NULL,
    mobile_money_phone character varying(20) NOT NULL,
    mobile_money_amount double precision NOT NULL,
    mobile_money_reference character varying(100) NOT NULL,
    notes character varying(500),
    status character varying(20) NOT NULL,
    validated_by character varying(100),
    validated_at timestamp(6) without time zone,
    rejected_by character varying(100),
    rejected_at timestamp(6) without time zone,
    rejection_reason character varying(500),
    CONSTRAINT customer_adhesion_type_check CHECK (adhesion_type IN ('PERSONAL', 'BUSINESS', 'EVENT')),
    CONSTRAINT customer_adhesion_kind_check CHECK (request_kind IN ('SUBSCRIBE', 'TOP_UP')),
    CONSTRAINT customer_adhesion_status_check CHECK (status IN ('INITIE', 'VALIDE', 'REJETE')),
    CONSTRAINT fk_customer_adhesion_client FOREIGN KEY (client_id) REFERENCES public.client(id)
);

CREATE INDEX IF NOT EXISTS idx_customer_adhesion_client_status
    ON public.customer_adhesion_submission (client_id, status);

