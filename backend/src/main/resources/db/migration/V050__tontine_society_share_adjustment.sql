-- Réajustement de la part société d'un membre tontine.
-- Le montant saisi (commercial, chef de recouvrement, gestionnaire) remplace le calcul automatique
-- et survit aux recalculs ; l'historique garde ce que l'application avait calculé.

ALTER TABLE public.tontine_member ADD COLUMN IF NOT EXISTS society_share_override double precision;
ALTER TABLE public.tontine_member ADD COLUMN IF NOT EXISTS society_share_computed double precision DEFAULT 0;
ALTER TABLE public.tontine_member ADD COLUMN IF NOT EXISTS society_share_status character varying(20) DEFAULT 'AUTO';
ALTER TABLE public.tontine_member ADD COLUMN IF NOT EXISTS society_share_locked boolean DEFAULT false;
ALTER TABLE public.tontine_member ADD COLUMN IF NOT EXISTS society_share_reviewed_at timestamp(6) without time zone;
ALTER TABLE public.tontine_member ADD COLUMN IF NOT EXISTS society_share_reviewed_by character varying(100);

UPDATE public.tontine_member
SET society_share_computed = COALESCE(society_share, 0)
WHERE society_share_override IS NULL;
UPDATE public.tontine_member SET society_share_status = 'AUTO' WHERE society_share_status IS NULL;
UPDATE public.tontine_member SET society_share_locked = false WHERE society_share_locked IS NULL;

CREATE TABLE IF NOT EXISTS public.tontine_society_share_adjustment (
    id bigint NOT NULL,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL,
    tontine_member_id bigint NOT NULL,
    tontine_session_id bigint,
    client_name character varying(255),
    commercial_username character varying(255),
    reference character varying(64),
    delivery_reference character varying(255),
    source character varying(30) NOT NULL,
    outcome character varying(20) NOT NULL,
    supervisor boolean NOT NULL DEFAULT false,
    regular_contribution double precision,
    computed_society_share double precision,
    previous_society_share double precision,
    declared_society_share double precision,
    new_society_share double precision,
    delta double precision,
    previous_available double precision,
    new_available double precision,
    comment text,
    adjusted_by character varying(100),
    adjusted_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT tontine_society_share_adjustment_pkey PRIMARY KEY (id),
    CONSTRAINT tontine_society_share_adjustment_reference_key UNIQUE (reference),
    CONSTRAINT tontine_society_share_adjustment_visibility_check CHECK (
        (visibility)::text = ANY (ARRAY[
            ('ENABLED'::character varying)::text,
            ('DISABLED'::character varying)::text,
            ('DELETED'::character varying)::text
        ])
    )
);

ALTER TABLE public.tontine_society_share_adjustment ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.tontine_society_share_adjustment_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE INDEX IF NOT EXISTS idx_tontine_society_share_adjustment_member
    ON public.tontine_society_share_adjustment (tontine_member_id, adjusted_at DESC);
CREATE INDEX IF NOT EXISTS idx_tontine_society_share_adjustment_kpi
    ON public.tontine_society_share_adjustment (commercial_username, adjusted_at);

-- Retour au calcul automatique : réservé aux administrateurs (par permission).
INSERT INTO uperm (reg_user_id, date_reg, visibility, permnam, permdfltnam)
SELECT 'System', NOW(), 'ENABLED', 'ROLE_RESET_TONTINE_SOCIETY_SHARE', 'ROLE_RESET_TONTINE_SOCIETY_SHARE'
WHERE NOT EXISTS (
    SELECT 1 FROM uperm WHERE permnam = 'ROLE_RESET_TONTINE_SOCIETY_SHARE'
);

INSERT INTO upro_perms (permid, proid)
SELECT u.permid, pr.proid
FROM uperm u
CROSS JOIN upro pr
WHERE u.permnam = 'ROLE_RESET_TONTINE_SOCIETY_SHARE'
  AND pr.name IN ('SUPER_ADMIN', 'ADMIN')
  AND NOT EXISTS (
      SELECT 1 FROM upro_perms up
      WHERE up.permid = u.permid AND up.proid = pr.proid
  );

INSERT INTO uacc_perms (accid, permid)
SELECT a.accid, u.permid
FROM uacc a
JOIN upro pr ON pr.proid = a.proid
JOIN uperm u ON u.permnam = 'ROLE_RESET_TONTINE_SOCIETY_SHARE'
WHERE pr.name IN ('SUPER_ADMIN', 'ADMIN')
  AND NOT EXISTS (
      SELECT 1 FROM uacc_perms ap
      WHERE ap.accid = a.accid AND ap.permid = u.permid
  );
