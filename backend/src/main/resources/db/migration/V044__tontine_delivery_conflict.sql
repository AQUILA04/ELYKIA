-- Journal des doublons de commande / livraison tontine.
-- Plusieurs téléphones partagent parfois le même compte commercial sans être synchronisés :
-- le serveur trace chaque seconde saisie pour le même membre (fusionnée ou refusée).

CREATE TABLE IF NOT EXISTS public.tontine_delivery_conflict (
    id bigint NOT NULL,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL,
    tontine_member_id bigint NOT NULL,
    tontine_session_id bigint,
    client_name character varying(255),
    commercial_username character varying(255),
    existing_delivery_id bigint,
    existing_reference character varying(255),
    existing_amount double precision,
    existing_delivery_date timestamp(6) without time zone,
    incoming_reference character varying(255),
    incoming_authenticity_code character varying(20),
    incoming_amount double precision,
    incoming_items text,
    available_balance double precision,
    operation character varying(30) NOT NULL,
    outcome character varying(30) NOT NULL,
    reason character varying(40) NOT NULL,
    device_id character varying(255),
    attempts integer NOT NULL DEFAULT 1,
    first_seen_at timestamp(6) without time zone NOT NULL,
    last_seen_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT tontine_delivery_conflict_pkey PRIMARY KEY (id),
    CONSTRAINT tontine_delivery_conflict_visibility_check CHECK (
        (visibility)::text = ANY (ARRAY[
            ('ENABLED'::character varying)::text,
            ('DISABLED'::character varying)::text,
            ('DELETED'::character varying)::text
        ])
    )
);

ALTER TABLE public.tontine_delivery_conflict ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.tontine_delivery_conflict_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE INDEX IF NOT EXISTS idx_tontine_delivery_conflict_last_seen
    ON public.tontine_delivery_conflict (last_seen_at DESC);

-- Le reçu imprimé par le second téléphone reste vérifiable après fusion.
CREATE INDEX IF NOT EXISTS idx_tontine_delivery_conflict_authenticity
    ON public.tontine_delivery_conflict (incoming_authenticity_code);

CREATE INDEX IF NOT EXISTS idx_tontine_delivery_conflict_member
    ON public.tontine_delivery_conflict (tontine_member_id, operation, incoming_reference);
