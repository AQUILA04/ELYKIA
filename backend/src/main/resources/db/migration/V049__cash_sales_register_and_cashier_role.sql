CREATE TABLE IF NOT EXISTS public.cash_sales_register_session (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_date      DATE             NOT NULL,
    cashier_username  VARCHAR(100)     NOT NULL,
    status            VARCHAR(20)      NOT NULL,
    opening_float     DOUBLE PRECISION NOT NULL DEFAULT 0,
    total_receipts    DOUBLE PRECISION NOT NULL DEFAULT 0,
    total_reversals   DOUBLE PRECISION NOT NULL DEFAULT 0,
    receipts_count    INTEGER          NOT NULL DEFAULT 0,
    reversals_count   INTEGER          NOT NULL DEFAULT 0,
    expected_closing  DOUBLE PRECISION NOT NULL DEFAULT 0,
    counted_closing   DOUBLE PRECISION,
    discrepancy       DOUBLE PRECISION,
    closing_notes     VARCHAR(255),
    opened_at         TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at         TIMESTAMP,
    closed_by         VARCHAR(100),
    CONSTRAINT ck_csrs_status CHECK (status IN ('OPEN', 'CLOSED'))
);
CREATE INDEX IF NOT EXISTS idx_csrs_date_status ON public.cash_sales_register_session (session_date, status);
CREATE INDEX IF NOT EXISTS idx_csrs_cashier ON public.cash_sales_register_session (cashier_username, session_date);

CREATE TABLE IF NOT EXISTS public.cash_sales_register_entry (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id         BIGINT           NOT NULL REFERENCES public.cash_sales_register_session (id),
    entry_type         VARCHAR(20)      NOT NULL,
    amount             DOUBLE PRECISION NOT NULL,
    signed_amount      DOUBLE PRECISION NOT NULL,
    sale_id            BIGINT,
    sale_reference     VARCHAR(100),
    client_id          BIGINT,
    client_name        VARCHAR(200),
    collector          VARCHAR(100),
    performed_by       VARCHAR(100)     NOT NULL,
    accounting_date    DATE             NOT NULL,
    occurred_at        TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes              VARCHAR(255),
    CONSTRAINT ck_csre_type CHECK (entry_type IN ('RECEIPT', 'REVERSAL'))
);
CREATE INDEX IF NOT EXISTS idx_csre_session ON public.cash_sales_register_entry (session_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_csre_date ON public.cash_sales_register_entry (accounting_date);
CREATE INDEX IF NOT EXISTS idx_csre_sale ON public.cash_sales_register_entry (sale_id);
