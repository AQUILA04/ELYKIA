INSERT INTO public.upro_perms (permid, proid)
SELECT u.permid, pr.proid
FROM public.uperm u
CROSS JOIN public.upro pr
WHERE u.permnam = 'ROLE_CASH_REGISTER_SALE'
  AND pr.name IN ('CASHIER', 'SECRETARY', 'GESTIONNAIRE', 'ADMIN', 'SUPER_ADMIN')
  AND NOT EXISTS (SELECT 1 FROM public.upro_perms up WHERE up.permid = u.permid AND up.proid = pr.proid);

