-- Plan 2 — Architecture DDD & Hexagonale : Portefeuille commercial multi-affectations (ACTIVE / INACTIVE),
-- historique d'audit consultable depuis le Frontend, et mandats de relais sur carnet Tontine (TontineMember).

-- ============================================================================
-- 1. Table client_commercial_assignment (1..N commerciaux par client et par activité)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.client_commercial_assignment (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id           BIGINT       NOT NULL REFERENCES public.client (id) ON DELETE CASCADE,
    commercial_username VARCHAR(100) NOT NULL,
    activity_type       VARCHAR(20)  NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    is_primary          BOOLEAN      NOT NULL DEFAULT FALSE,
    assigned_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_activated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deactivated_at      TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by          VARCHAR(100),
    status_reason       VARCHAR(255),
    CONSTRAINT uk_client_commercial_assignment UNIQUE (client_id, commercial_username, activity_type),
    CONSTRAINT ck_cca_activity CHECK (activity_type IN ('CREDIT', 'TONTINE', 'AGENCY', 'RECOVERY')),
    CONSTRAINT ck_cca_status   CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE INDEX IF NOT EXISTS idx_cca_client_activity ON public.client_commercial_assignment (client_id, activity_type, status);
CREATE INDEX IF NOT EXISTS idx_cca_commercial_status ON public.client_commercial_assignment (commercial_username, activity_type, status);

-- ============================================================================
-- 2. Table client_commercial_assignment_history (journal immuable consultable depuis le Frontend)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.client_commercial_assignment_history (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id       BIGINT REFERENCES public.client_commercial_assignment (id) ON DELETE SET NULL,
    client_id           BIGINT       NOT NULL REFERENCES public.client (id) ON DELETE CASCADE,
    commercial_username VARCHAR(100) NOT NULL,
    activity_type       VARCHAR(20)  NOT NULL,
    event_type          VARCHAR(30)  NOT NULL,
    previous_status     VARCHAR(20),
    new_status          VARCHAR(20)  NOT NULL,
    was_primary         BOOLEAN      NOT NULL DEFAULT FALSE,
    is_primary          BOOLEAN      NOT NULL DEFAULT FALSE,
    replaced_by_commercial_username VARCHAR(100),
    reason              VARCHAR(255),
    performed_by        VARCHAR(100) NOT NULL,
    occurred_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ccah_activity CHECK (activity_type IN ('CREDIT', 'TONTINE', 'AGENCY', 'RECOVERY')),
    CONSTRAINT ck_ccah_event CHECK (event_type IN (
        'ASSIGNED', 'ACTIVATED', 'DEACTIVATED', 'REACTIVATED', 'PROMOTED_PRIMARY', 'DEMOTED_PRIMARY', 'RELAY_HANDOVER'
    ))
);
CREATE INDEX IF NOT EXISTS idx_ccah_client_date ON public.client_commercial_assignment_history (client_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_ccah_commercial_date ON public.client_commercial_assignment_history (commercial_username, occurred_at DESC);

-- ============================================================================
-- 3. Table tontine_member_commercial_assignment (mandats Initiateur / Relais / Co-collecteur sur carnet tontine)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.tontine_member_commercial_assignment (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tontine_member_id           BIGINT       NOT NULL REFERENCES public.tontine_member (id) ON DELETE CASCADE,
    commercial_username         VARCHAR(100) NOT NULL,
    status                      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    role                        VARCHAR(20)  NOT NULL DEFAULT 'INITIATOR',
    effective_from              DATE         NOT NULL DEFAULT CURRENT_DATE,
    effective_to                DATE,
    collections_count_snapshot  BIGINT       NOT NULL DEFAULT 0,
    collections_amount_snapshot DOUBLE PRECISION NOT NULL DEFAULT 0,
    assigned_by                 VARCHAR(100),
    reason                      VARCHAR(255),
    created_at                  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_tmca_member_commercial UNIQUE (tontine_member_id, commercial_username),
    CONSTRAINT ck_tmca_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_tmca_role   CHECK (role IN ('INITIATOR', 'RELAY', 'CO_COLLECTOR'))
);
CREATE INDEX IF NOT EXISTS idx_tmca_member_status ON public.tontine_member_commercial_assignment (tontine_member_id, status);
CREATE INDEX IF NOT EXISTS idx_tmca_commercial_status ON public.tontine_member_commercial_assignment (commercial_username, status);

-- ============================================================================
-- 4. Backfill idempotent depuis les données existantes (client, client_collector_history, tontine_member, tontine_collection)
-- ============================================================================
DO $$
BEGIN
    -- 4.1 Affectations ACTIVE principales depuis la table client
    INSERT INTO public.client_commercial_assignment
        (client_id, commercial_username, activity_type, status, is_primary, assigned_at, last_activated_at, updated_by, status_reason)
    SELECT c.id, TRIM(COALESCE(c.credit_commercial_username, c.collector)), 'CREDIT', 'ACTIVE', TRUE,
           COALESCE(c.date_reg, CURRENT_TIMESTAMP), COALESCE(c.date_reg, CURRENT_TIMESTAMP), 'migration-v051', 'Reprise titulaire crédit actuel'
    FROM public.client c
    WHERE TRIM(COALESCE(c.credit_commercial_username, c.collector, '')) <> ''
    ON CONFLICT (client_id, commercial_username, activity_type) DO NOTHING;

    INSERT INTO public.client_commercial_assignment
        (client_id, commercial_username, activity_type, status, is_primary, assigned_at, last_activated_at, updated_by, status_reason)
    SELECT c.id, TRIM(COALESCE(c.tontine_commercial_username, c.tontine_collector)), 'TONTINE', 'ACTIVE', TRUE,
           COALESCE(c.date_reg, CURRENT_TIMESTAMP), COALESCE(c.date_reg, CURRENT_TIMESTAMP), 'migration-v051', 'Reprise titulaire tontine actuel'
    FROM public.client c
    WHERE TRIM(COALESCE(c.tontine_commercial_username, c.tontine_collector, '')) <> ''
    ON CONFLICT (client_id, commercial_username, activity_type) DO NOTHING;

    INSERT INTO public.client_commercial_assignment
        (client_id, commercial_username, activity_type, status, is_primary, assigned_at, last_activated_at, updated_by, status_reason)
    SELECT c.id, TRIM(COALESCE(c.agency_commercial_username, c.agency_collector)), 'AGENCY', 'ACTIVE', TRUE,
           COALESCE(c.date_reg, CURRENT_TIMESTAMP), COALESCE(c.date_reg, CURRENT_TIMESTAMP), 'migration-v051', 'Reprise titulaire agence actuel'
    FROM public.client c
    WHERE TRIM(COALESCE(c.agency_commercial_username, c.agency_collector, '')) <> ''
    ON CONFLICT (client_id, commercial_username, activity_type) DO NOTHING;

    INSERT INTO public.client_commercial_assignment
        (client_id, commercial_username, activity_type, status, is_primary, assigned_at, last_activated_at, updated_by, status_reason)
    SELECT c.id, TRIM(COALESCE(c.recovery_commercial_username, c.recovery_collector)), 'RECOVERY', 'ACTIVE', TRUE,
           COALESCE(c.date_reg, CURRENT_TIMESTAMP), COALESCE(c.date_reg, CURRENT_TIMESTAMP), 'migration-v051', 'Reprise titulaire recouvrement actuel'
    FROM public.client c
    WHERE TRIM(COALESCE(c.recovery_commercial_username, c.recovery_collector, '')) <> ''
    ON CONFLICT (client_id, commercial_username, activity_type) DO NOTHING;

    -- 4.2 Anciens commerciaux depuis client_collector_history -> INACTIVE (consultation de leurs propres opérations)
    INSERT INTO public.client_commercial_assignment
        (client_id, commercial_username, activity_type, status, is_primary, assigned_at, last_activated_at, deactivated_at, updated_by, status_reason)
    SELECT h.client_id,
           TRIM(COALESCE(h.old_commercial_username, h.old_collector)),
           h.collector_type,
           'INACTIVE',
           FALSE,
           MIN(h.change_date),
           MIN(h.change_date),
           MAX(h.change_date),
           'migration-v051',
           'Ancien commercial (historique réaffectation)'
    FROM public.client_collector_history h
    JOIN public.client c ON c.id = h.client_id
    WHERE TRIM(COALESCE(h.old_commercial_username, h.old_collector, '')) <> ''
      AND h.collector_type IN ('CREDIT', 'TONTINE', 'AGENCY', 'RECOVERY')
    GROUP BY h.client_id, TRIM(COALESCE(h.old_commercial_username, h.old_collector)), h.collector_type
    ON CONFLICT (client_id, commercial_username, activity_type) DO NOTHING;

    -- 4.3 Historique initial si la table d'historique est vide
    IF NOT EXISTS (SELECT 1 FROM public.client_commercial_assignment_history) THEN
        INSERT INTO public.client_commercial_assignment_history
            (assignment_id, client_id, commercial_username, activity_type, event_type, previous_status, new_status,
             was_primary, is_primary, reason, performed_by, occurred_at)
        SELECT a.id, a.client_id, a.commercial_username, a.activity_type,
               CASE WHEN a.status = 'ACTIVE' THEN 'ASSIGNED' ELSE 'DEACTIVATED' END,
               NULL, a.status, FALSE, a.is_primary, a.status_reason, COALESCE(a.updated_by, 'migration-v051'), a.assigned_at
        FROM public.client_commercial_assignment a;
    END IF;

    -- 4.4 Mandats sur les carnets tontine (tontine_member_commercial_assignment)
    INSERT INTO public.tontine_member_commercial_assignment
        (tontine_member_id, commercial_username, status, role, effective_from, assigned_by, reason)
    SELECT tm.id,
           TRIM(COALESCE(c.tontine_commercial_username, c.tontine_collector)),
           'ACTIVE',
           'INITIATOR',
           COALESCE(tm.registration_date, CURRENT_DATE),
           'migration-v051',
           'Titulaire tontine actuel'
    FROM public.tontine_member tm
    JOIN public.client c ON c.id = tm.client_id
    WHERE TRIM(COALESCE(c.tontine_commercial_username, c.tontine_collector, '')) <> ''
    ON CONFLICT (tontine_member_id, commercial_username) DO NOTHING;

    -- Commerciaux ayant déjà collecté sur un carnet mais n'étant plus le titulaire actuel -> mandat INACTIVE
    INSERT INTO public.tontine_member_commercial_assignment
        (tontine_member_id, commercial_username, status, role, effective_from, effective_to,
         collections_count_snapshot, collections_amount_snapshot, assigned_by, reason)
    SELECT tc.tontine_member_id,
           TRIM(tc.commercial_username),
           'INACTIVE',
           'INITIATOR',
           MIN(tc.collection_date)::date,
           MAX(tc.collection_date)::date,
           COUNT(*),
           COALESCE(SUM(tc.amount), 0),
           'migration-v051',
           'Collectes historiques réalisées sur ce carnet'
    FROM public.tontine_collection tc
    WHERE TRIM(COALESCE(tc.commercial_username, '')) <> ''
      AND tc.visibility = 'ENABLED'
    GROUP BY tc.tontine_member_id, TRIM(tc.commercial_username)
    ON CONFLICT (tontine_member_id, commercial_username) DO UPDATE
    SET collections_count_snapshot  = EXCLUDED.collections_count_snapshot,
        collections_amount_snapshot = EXCLUDED.collections_amount_snapshot;
END;
$$;
