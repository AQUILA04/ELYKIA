-- Commercial Stock — modèle continu (Phase 1) : positions, couches FIFO, ledger, traçabilité de consommation, snapshots.
-- Additif uniquement : aucune table historique (commercial_monthly_stock*, tontine_stock*) n'est modifiée.

CREATE TABLE IF NOT EXISTS public.commercial_stock_position (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collector                 VARCHAR(100)     NOT NULL,
    article_id                BIGINT           NOT NULL REFERENCES public.articles (id),
    activity_type             VARCHAR(20)      NOT NULL,
    quantity_on_hand          INTEGER          NOT NULL DEFAULT 0,
    weighted_avg_purchase_cost DOUBLE PRECISION,
    current_sale_unit_price   DOUBLE PRECISION,
    version                   BIGINT           NOT NULL DEFAULT 0,
    created_at                TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_commercial_stock_position UNIQUE (collector, article_id, activity_type),
    CONSTRAINT ck_commercial_stock_position_qty CHECK (quantity_on_hand >= 0),
    CONSTRAINT ck_commercial_stock_position_activity CHECK (activity_type IN ('CREDIT', 'TONTINE'))
);
CREATE INDEX IF NOT EXISTS idx_csp_collector_activity ON public.commercial_stock_position (collector, activity_type);
CREATE INDEX IF NOT EXISTS idx_csp_article ON public.commercial_stock_position (article_id);

CREATE TABLE IF NOT EXISTS public.commercial_stock_layer (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_id              BIGINT           NOT NULL REFERENCES public.commercial_stock_position (id),
    quantity_initial         INTEGER          NOT NULL,
    quantity_remaining       INTEGER          NOT NULL,
    unit_purchase_cost       DOUBLE PRECISION NOT NULL,
    initial_sale_price       DOUBLE PRECISION,
    effective_sale_price     DOUBLE PRECISION,
    packaging_type           VARCHAR(30),
    units_per_package        INTEGER,
    units_per_half_package   INTEGER,
    wholesale_sale_price     DOUBLE PRECISION,
    half_wholesale_sale_price DOUBLE PRECISION,
    source_type              VARCHAR(30)      NOT NULL,
    source_id                BIGINT,
    acquired_at              TIMESTAMP        NOT NULL,
    CONSTRAINT ck_csl_quantities CHECK (quantity_remaining >= 0 AND quantity_remaining <= quantity_initial)
);
CREATE INDEX IF NOT EXISTS idx_csl_position_acquired_open
    ON public.commercial_stock_layer (position_id, acquired_at, id) WHERE quantity_remaining > 0;

CREATE TABLE IF NOT EXISTS public.commercial_stock_ledger_entry (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_id           BIGINT           NOT NULL REFERENCES public.commercial_stock_position (id),
    collector             VARCHAR(100)     NOT NULL,
    article_id            BIGINT           NOT NULL,
    activity_type         VARCHAR(20)      NOT NULL,
    movement_type         VARCHAR(30)      NOT NULL,
    delta_quantity        INTEGER          NOT NULL,
    quantity_before       INTEGER          NOT NULL,
    quantity_after        INTEGER          NOT NULL,
    unit_purchase_cost    DOUBLE PRECISION,
    unit_sale_price       DOUBLE PRECISION,
    previous_sale_price   DOUBLE PRECISION,
    total_sale_value      DOUBLE PRECISION,
    total_purchase_value  DOUBLE PRECISION,
    margin_amount         DOUBLE PRECISION,
    reference_type        VARCHAR(30),
    reference_id          BIGINT,
    reference_code        VARCHAR(100),
    tontine_session_id    BIGINT,
    transfer_id           VARCHAR(40),
    reverses_movement_id  BIGINT           REFERENCES public.commercial_stock_ledger_entry (id),
    accounting_date       DATE             NOT NULL,
    occurred_at           TIMESTAMP        NOT NULL,
    backdated             BOOLEAN          NOT NULL DEFAULT FALSE,
    backdated_reason      VARCHAR(255),
    performed_by          VARCHAR(100)
);
CREATE INDEX IF NOT EXISTS idx_csm_collector_activity_date
    ON public.commercial_stock_ledger_entry (collector, activity_type, accounting_date);
CREATE INDEX IF NOT EXISTS idx_csm_position_occurred ON public.commercial_stock_ledger_entry (position_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_csm_position_accounting ON public.commercial_stock_ledger_entry (position_id, accounting_date);
CREATE INDEX IF NOT EXISTS idx_csm_reference ON public.commercial_stock_ledger_entry (reference_type, reference_id);
CREATE INDEX IF NOT EXISTS idx_csm_tontine_session ON public.commercial_stock_ledger_entry (tontine_session_id)
    WHERE tontine_session_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uk_csm_reverses ON public.commercial_stock_ledger_entry (reverses_movement_id)
    WHERE reverses_movement_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.commercial_stock_layer_consumption (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_id        BIGINT           NOT NULL REFERENCES public.commercial_stock_ledger_entry (id),
    layer_id           BIGINT           NOT NULL REFERENCES public.commercial_stock_layer (id),
    quantity           INTEGER          NOT NULL,
    unit_purchase_cost DOUBLE PRECISION NOT NULL,
    unit_sale_price    DOUBLE PRECISION
);
CREATE INDEX IF NOT EXISTS idx_cslc_movement ON public.commercial_stock_layer_consumption (movement_id);
CREATE INDEX IF NOT EXISTS idx_cslc_layer ON public.commercial_stock_layer_consumption (layer_id);

CREATE TABLE IF NOT EXISTS public.commercial_stock_period_snapshot (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collector               VARCHAR(100)     NOT NULL,
    article_id              BIGINT           NOT NULL,
    activity_type           VARCHAR(20)      NOT NULL,
    period_grain            VARCHAR(20)      NOT NULL,
    period_year             INTEGER          NOT NULL,
    period_month            INTEGER,
    tontine_session_id      BIGINT,
    period_start            DATE             NOT NULL,
    period_end              DATE             NOT NULL,
    opening_quantity        INTEGER          NOT NULL,
    in_quantity             INTEGER          NOT NULL,
    sold_quantity           INTEGER          NOT NULL,
    returned_quantity       INTEGER          NOT NULL,
    transfer_net_quantity   INTEGER          NOT NULL,
    debt_quantity           INTEGER          NOT NULL,
    adjustment_net_quantity INTEGER          NOT NULL,
    closing_quantity        INTEGER          NOT NULL,
    opening_purchase_value  DOUBLE PRECISION,
    closing_purchase_value  DOUBLE PRECISION,
    closing_sale_value      DOUBLE PRECISION,
    sold_value              DOUBLE PRECISION,
    purchase_cost_of_sold   DOUBLE PRECISION,
    realized_margin         DOUBLE PRECISION,
    closed_at               TIMESTAMP        NOT NULL,
    restated_at             TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_csps_period ON public.commercial_stock_period_snapshot
    (collector, article_id, activity_type, period_grain, period_year, COALESCE(period_month, 0), COALESCE(tontine_session_id, 0));
