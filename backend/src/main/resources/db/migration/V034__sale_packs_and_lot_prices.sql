CREATE TABLE IF NOT EXISTS tontine_stock_layer (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tontine_stock_id bigint NOT NULL REFERENCES tontine_stock (id),
    quantity_initial integer NOT NULL,
    quantity_remaining integer NOT NULL,
    unit_purchase_price double precision NOT NULL,
    unit_sale_price double precision,
    wholesale_purchase_price double precision,
    wholesale_sale_price double precision,
    half_wholesale_purchase_price double precision,
    half_wholesale_sale_price double precision,
    units_per_package integer,
    units_per_half_package integer,
    packaging_type character varying(32)
);

CREATE INDEX IF NOT EXISTS idx_tontine_stock_layer_stock ON tontine_stock_layer (tontine_stock_id, id);

