CREATE TABLE IF NOT EXISTS stock_reception_item_sale_pack (
    reception_item_id bigint NOT NULL REFERENCES stock_reception_item (id) ON DELETE CASCADE,
    quantity integer NOT NULL,
    sale_price double precision NOT NULL
);

CREATE TABLE IF NOT EXISTS tontine_stock_layer_sale_pack (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layer_id bigint NOT NULL REFERENCES tontine_stock_layer (id) ON DELETE CASCADE,
    quantity integer NOT NULL,
    sale_price double precision NOT NULL,
    CONSTRAINT uk_tontine_layer_sale_pack UNIQUE (layer_id, quantity)
);
