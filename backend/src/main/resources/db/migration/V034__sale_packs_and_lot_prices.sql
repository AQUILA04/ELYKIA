-- Demi-gros optionnel, prix de vente au pack, prix figés sur le lot FIFO.

ALTER TABLE articles ADD COLUMN IF NOT EXISTS units_per_half_package integer;
ALTER TABLE articles ADD COLUMN IF NOT EXISTS wholesale_sale_price double precision;
ALTER TABLE articles ADD COLUMN IF NOT EXISTS half_wholesale_sale_price double precision;

CREATE TABLE IF NOT EXISTS article_sale_pack (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id bigint NOT NULL REFERENCES articles (id),
    quantity integer NOT NULL,
    sale_price double precision NOT NULL,
    CONSTRAINT article_sale_pack_quantity_check CHECK (quantity >= 2),
    CONSTRAINT article_sale_pack_price_check CHECK (sale_price > 0),
    CONSTRAINT uk_article_sale_pack UNIQUE (article_id, quantity)
);

ALTER TABLE article_stock_lot ADD COLUMN IF NOT EXISTS unit_sale_price double precision;
ALTER TABLE article_stock_lot ADD COLUMN IF NOT EXISTS wholesale_sale_price double precision;
ALTER TABLE article_stock_lot ADD COLUMN IF NOT EXISTS half_wholesale_sale_price double precision;
ALTER TABLE article_stock_lot ADD COLUMN IF NOT EXISTS wholesale_purchase_price double precision;
ALTER TABLE article_stock_lot ADD COLUMN IF NOT EXISTS half_wholesale_purchase_price double precision;
ALTER TABLE article_stock_lot ADD COLUMN IF NOT EXISTS units_per_package integer;
ALTER TABLE article_stock_lot ADD COLUMN IF NOT EXISTS units_per_half_package integer;
ALTER TABLE article_stock_lot ADD COLUMN IF NOT EXISTS packaging_type character varying(32);

CREATE TABLE IF NOT EXISTS article_stock_lot_sale_pack (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id bigint NOT NULL REFERENCES article_stock_lot (id) ON DELETE CASCADE,
    quantity integer NOT NULL,
    sale_price double precision NOT NULL,
    CONSTRAINT uk_lot_sale_pack UNIQUE (lot_id, quantity)
);

