-- Annuaire des personnes qui utilisent les comptes commerciaux, et historique d'affectation.
-- Deux périodes ne se chevauchent ni sur un compte, ni pour une même personne.

ALTER TABLE public.promoter
    ADD COLUMN IF NOT EXISTS photo_object_key character varying(255);

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS public.commercial_account_assignment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL DEFAULT 'ENABLED',
    user_id bigint NOT NULL,
    promoter_id bigint NOT NULL,
    start_date date NOT NULL,
    end_date date,
    CONSTRAINT commercial_account_assignment_visibility_check CHECK (
        (visibility)::text = ANY (ARRAY['ENABLED'::text, 'DISABLED'::text, 'DELETED'::text])
    ),
    CONSTRAINT commercial_account_assignment_dates_check CHECK (
        end_date IS NULL OR end_date >= start_date
    ),
    CONSTRAINT fk_commercial_assignment_user FOREIGN KEY (user_id) REFERENCES public.users (useid),
    CONSTRAINT fk_commercial_assignment_promoter FOREIGN KEY (promoter_id) REFERENCES public.promoter (id)
);

ALTER TABLE public.commercial_account_assignment
    DROP CONSTRAINT IF EXISTS commercial_assignment_account_no_overlap;

ALTER TABLE public.commercial_account_assignment
    ADD CONSTRAINT commercial_assignment_account_no_overlap
    EXCLUDE USING gist (
        user_id WITH =,
        daterange(start_date, COALESCE(end_date, 'infinity'::date), '[]') WITH &&
    ) WHERE (visibility = 'ENABLED');

ALTER TABLE public.commercial_account_assignment
    DROP CONSTRAINT IF EXISTS commercial_assignment_person_no_overlap;

ALTER TABLE public.commercial_account_assignment
    ADD CONSTRAINT commercial_assignment_person_no_overlap
    EXCLUDE USING gist (
        promoter_id WITH =,
        daterange(start_date, COALESCE(end_date, 'infinity'::date), '[]') WITH &&
    ) WHERE (visibility = 'ENABLED');

INSERT INTO uperm (reg_user_id, date_reg, visibility, permnam, permdfltnam)
SELECT 'System', NOW(), 'ENABLED', 'ROLE_MANAGE_COMMERCIAL_STAFF', 'ROLE_MANAGE_COMMERCIAL_STAFF'
WHERE NOT EXISTS (
    SELECT 1 FROM uperm WHERE permnam = 'ROLE_MANAGE_COMMERCIAL_STAFF'
);

INSERT INTO upro_perms (permid, proid)
SELECT u.permid, pr.proid
FROM uperm u
CROSS JOIN upro pr
WHERE u.permnam = 'ROLE_MANAGE_COMMERCIAL_STAFF'
  AND pr.name IN ('GESTIONNAIRE', 'SECRETARY', 'ADMIN', 'SUPER_ADMIN')
  AND NOT EXISTS (
      SELECT 1 FROM upro_perms up
      WHERE up.permid = u.permid AND up.proid = pr.proid
  );

INSERT INTO uacc_perms (accid, permid)
SELECT a.accid, u.permid
FROM uacc a
JOIN upro pr ON pr.proid = a.proid
JOIN uperm u ON u.permnam = 'ROLE_MANAGE_COMMERCIAL_STAFF'
WHERE pr.name IN ('GESTIONNAIRE', 'SECRETARY', 'ADMIN', 'SUPER_ADMIN')
  AND NOT EXISTS (
      SELECT 1 FROM uacc_perms ap
      WHERE ap.accid = a.accid AND ap.permid = u.permid
  );
