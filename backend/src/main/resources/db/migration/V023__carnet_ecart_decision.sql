-- Décision du commercial sur un écart de contrôle de carnet, et origine des manquants de caisse.

CREATE TABLE IF NOT EXISTS public.carnet_ecart_decision (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL DEFAULT 'ENABLED',
    domain character varying(20) NOT NULL,
    credit_field_control_id bigint,
    tontine_field_control_id bigint,
    tontine_line_id bigint,
    commercial_username character varying(100) NOT NULL,
    system_amount double precision NOT NULL,
    notebook_amount double precision NOT NULL,
    difference_amount double precision NOT NULL,
    direction character varying(40) NOT NULL,
    status character varying(20) NOT NULL,
    rejection_note character varying(1000),
    decided_by character varying(100) NOT NULL,
    decided_at timestamp(6) without time zone NOT NULL,
    mise_reference character varying(64),
    debt_document_id bigint,
    operation_date date,
    CONSTRAINT carnet_ecart_decision_visibility_check CHECK (((visibility)::text = ANY (ARRAY[('ENABLED'::character varying)::text, ('DISABLED'::character varying)::text, ('DELETED'::character varying)::text]))),
    CONSTRAINT fk_carnet_ecart_credit_control FOREIGN KEY (credit_field_control_id) REFERENCES public.credit_field_control(id),
    CONSTRAINT fk_carnet_ecart_tontine_control FOREIGN KEY (tontine_field_control_id) REFERENCES public.tontine_member_field_control(id),
    CONSTRAINT fk_carnet_ecart_tontine_line FOREIGN KEY (tontine_line_id) REFERENCES public.tontine_member_field_control_line(id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_carnet_ecart_credit_control
    ON public.carnet_ecart_decision (credit_field_control_id)
    WHERE credit_field_control_id IS NOT NULL AND visibility = 'ENABLED';

CREATE UNIQUE INDEX IF NOT EXISTS uk_carnet_ecart_tontine_line
    ON public.carnet_ecart_decision (tontine_line_id)
    WHERE tontine_line_id IS NOT NULL AND visibility = 'ENABLED';

CREATE INDEX IF NOT EXISTS idx_carnet_ecart_commercial_status
    ON public.carnet_ecart_decision (commercial_username, status);

ALTER TABLE public.debt_document
    ADD COLUMN IF NOT EXISTS debt_origin character varying(30) NOT NULL DEFAULT 'CASH_CONSTITUTION',
    ADD COLUMN IF NOT EXISTS cash_category character varying(20),
    ADD COLUMN IF NOT EXISTS carnet_ecart_decision_id bigint;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_debt_document_carnet_ecart'
    ) THEN
        ALTER TABLE public.debt_document
            ADD CONSTRAINT fk_debt_document_carnet_ecart
            FOREIGN KEY (carnet_ecart_decision_id) REFERENCES public.carnet_ecart_decision(id);
    END IF;
END $$;

-- Les manquants issus d'un carnet peuvent coexister avec la constitution du jour.
DROP INDEX IF EXISTS public.uk_debt_document_active_period;

CREATE UNIQUE INDEX IF NOT EXISTS uk_debt_document_active_period
    ON public.debt_document (holder_username, debt_type, period_grain, period_year, COALESCE(period_month, 0), COALESCE(period_day, DATE '1900-01-01'))
    WHERE status <> 'CANCELLED'
      AND visibility = 'ENABLED'
      AND (debt_origin IS NULL OR debt_origin = 'CASH_CONSTITUTION');

CREATE INDEX IF NOT EXISTS idx_debt_document_field_control_day
    ON public.debt_document (holder_username, period_day)
    WHERE debt_origin = 'FIELD_CONTROL' AND status <> 'CANCELLED';
