-- Trace d'audit des équilibrages de surplus vers manquants crédit / tontine / solde.

CREATE TABLE IF NOT EXISTS public.cash_surplus_reallocation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL DEFAULT 'ENABLED',
    commercial_username character varying(255) NOT NULL,
    period_start date NOT NULL,
    period_end date NOT NULL,
    performed_at timestamp(6) without time zone NOT NULL,
    performed_by character varying(100) NOT NULL,
    surplus_before double precision NOT NULL DEFAULT 0,
    credit_allocated double precision NOT NULL DEFAULT 0,
    tontine_allocated double precision NOT NULL DEFAULT 0,
    new_balance_allocated double precision NOT NULL DEFAULT 0,
    surplus_remaining double precision NOT NULL DEFAULT 0,
    remaining_before double precision NOT NULL DEFAULT 0,
    remaining_after double precision NOT NULL DEFAULT 0,
    total_reallocated double precision NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_csr_commercial_period
    ON public.cash_surplus_reallocation (commercial_username, period_start, period_end);

CREATE INDEX IF NOT EXISTS idx_csr_performed_at
    ON public.cash_surplus_reallocation (performed_at DESC);

CREATE TABLE IF NOT EXISTS public.cash_surplus_reallocation_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reallocation_id bigint NOT NULL,
    cash_deposit_id bigint,
    deposit_reference character varying(255),
    deposit_date date NOT NULL,
    surplus_taken double precision NOT NULL DEFAULT 0,
    credit_allocated double precision NOT NULL DEFAULT 0,
    tontine_allocated double precision NOT NULL DEFAULT 0,
    new_balance_allocated double precision NOT NULL DEFAULT 0,
    CONSTRAINT fk_csrl_reallocation
        FOREIGN KEY (reallocation_id) REFERENCES public.cash_surplus_reallocation (id)
);

CREATE INDEX IF NOT EXISTS idx_csrl_reallocation
    ON public.cash_surplus_reallocation_line (reallocation_id);
