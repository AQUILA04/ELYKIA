CREATE INDEX IF NOT EXISTS idx_wsle_agency_article_occurred
    ON public.warehouse_stock_ledger_entry (agency_id, article_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_wsle_reference
    ON public.warehouse_stock_ledger_entry (reference_type, reference_id);

-- ============================================================================
-- 5. Inter-Agency Stock Transfers (piloted by STOREKEEPER_MANAGER)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.warehouse_stock_transfer (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference        VARCHAR(100) NOT NULL UNIQUE,
    source_agency_id BIGINT       NOT NULL REFERENCES public.agency (id),
    target_agency_id BIGINT       NOT NULL REFERENCES public.agency (id),
    status           VARCHAR(30)  NOT NULL,
    note             VARCHAR(500),
    created_by       VARCHAR(100) NOT NULL,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    validated_by     VARCHAR(100),
    validated_at     TIMESTAMP,
    shipped_by       VARCHAR(100),
    shipped_at       TIMESTAMP,
    received_by      VARCHAR(100),
    received_at      TIMESTAMP,
    cancelled_by     VARCHAR(100),
    cancelled_at     TIMESTAMP,
    CONSTRAINT ck_wst_agencies CHECK (source_agency_id <> target_agency_id),
    CONSTRAINT ck_wst_status CHECK (status IN ('CREATED', 'VALIDATED', 'SHIPPED', 'RECEIVED', 'CANCELLED'))
