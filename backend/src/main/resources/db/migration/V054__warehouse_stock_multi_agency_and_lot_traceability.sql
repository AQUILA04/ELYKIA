-- ============================================================================
-- 2. Warehouse Stock Position (per agency_id, article_id)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.warehouse_stock_position (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id           BIGINT           NOT NULL REFERENCES public.agency (id),
    article_id          BIGINT           NOT NULL REFERENCES public.articles (id),
    on_hand_quantity    INTEGER          NOT NULL DEFAULT 0,
    reserved_quantity   INTEGER          NOT NULL DEFAULT 0,
    reorder_point       INTEGER,
    optimal_stock_level INTEGER,
    last_restock_date   DATE,
    version             BIGINT           NOT NULL DEFAULT 0,
    created_at          TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_warehouse_stock_position UNIQUE (agency_id, article_id),
    CONSTRAINT ck_wsp_on_hand CHECK (on_hand_quantity >= 0),
    CONSTRAINT ck_wsp_reserved CHECK (reserved_quantity >= 0 AND reserved_quantity <= on_hand_quantity)
);
CREATE INDEX IF NOT EXISTS idx_wsp_agency ON public.warehouse_stock_position (agency_id);
CREATE INDEX IF NOT EXISTS idx_wsp_article ON public.warehouse_stock_position (article_id);

-- ============================================================================
-- 3. Warehouse Stock Reservation
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.warehouse_stock_reservation (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id          BIGINT      NOT NULL REFERENCES public.agency (id),
    article_id         BIGINT      NOT NULL REFERENCES public.articles (id),
    reservation_type   VARCHAR(40) NOT NULL,
    reference_id       BIGINT      NOT NULL,
    reference_code     VARCHAR(100),
    beneficiary        VARCHAR(100),
    quantity_requested INTEGER     NOT NULL,
    quantity_reserved  INTEGER     NOT NULL DEFAULT 0,
    shortage_quantity  INTEGER     NOT NULL DEFAULT 0,
    status             VARCHAR(30) NOT NULL,
    created_at         TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at        TIMESTAMP,
    performed_by       VARCHAR(100),
    CONSTRAINT ck_wsr_type CHECK (reservation_type IN ('CASH_SALE', 'COMMERCIAL_STOCK_REQUEST', 'TRANSFER')),
    CONSTRAINT ck_wsr_status CHECK (status IN ('ACTIVE', 'PARTIALLY_RESERVED', 'BACKORDERED', 'FULFILLED', 'RELEASED')),
    CONSTRAINT ck_wsr_quantities CHECK (quantity_requested > 0 AND quantity_reserved >= 0 AND shortage_quantity >= 0)
);
CREATE INDEX IF NOT EXISTS idx_wsr_agency_article_status
    ON public.warehouse_stock_reservation (agency_id, article_id, status);
CREATE INDEX IF NOT EXISTS idx_wsr_reference
    ON public.warehouse_stock_reservation (reservation_type, reference_id);

-- ============================================================================
-- 4. Warehouse Stock Ledger Entry (Unified append-only warehouse journal)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.warehouse_stock_ledger_entry (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id         BIGINT           NOT NULL REFERENCES public.agency (id),
    article_id        BIGINT           NOT NULL REFERENCES public.articles (id),
    movement_type     VARCHAR(40)      NOT NULL,
    quantity_delta    INTEGER          NOT NULL,
    on_hand_before    INTEGER          NOT NULL,
    on_hand_after     INTEGER          NOT NULL,
    reserved_before   INTEGER          NOT NULL DEFAULT 0,
    reserved_after    INTEGER          NOT NULL DEFAULT 0,
    unit_cost         DOUBLE PRECISION,
    total_cost        DOUBLE PRECISION,
    reference_type    VARCHAR(50),
    reference_id      BIGINT,
    reference_code    VARCHAR(100),
    beneficiary       VARCHAR(255),
    reason            VARCHAR(1000),
    performed_by      VARCHAR(100),
    operation_date    DATE             NOT NULL,
    occurred_at       TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP
