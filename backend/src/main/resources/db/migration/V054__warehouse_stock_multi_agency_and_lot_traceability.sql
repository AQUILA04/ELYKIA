CREATE INDEX IF NOT EXISTS idx_wst_source_agency ON public.warehouse_stock_transfer (source_agency_id, status);
CREATE INDEX IF NOT EXISTS idx_wst_target_agency ON public.warehouse_stock_transfer (target_agency_id, status);

CREATE TABLE IF NOT EXISTS public.warehouse_stock_transfer_item (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id         BIGINT           NOT NULL REFERENCES public.warehouse_stock_transfer (id) ON DELETE CASCADE,
    article_id          BIGINT           NOT NULL REFERENCES public.articles (id),
    article_name        TEXT,
    quantity_requested  INTEGER          NOT NULL,
    quantity_shipped    INTEGER          NOT NULL DEFAULT 0,
    quantity_received   INTEGER          NOT NULL DEFAULT 0,
