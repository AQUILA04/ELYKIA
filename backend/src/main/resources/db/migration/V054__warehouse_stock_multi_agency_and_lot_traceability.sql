-- ============================================================================
-- 8. Idempotent Backfill
-- ============================================================================
DO $$
DECLARE
    default_agency_id BIGINT;
BEGIN
    SELECT id INTO default_agency_id FROM public.agency WHERE code = 'DEFAULT' LIMIT 1;
    IF default_agency_id IS NULL THEN
        SELECT id INTO default_agency_id FROM public.agency ORDER BY id ASC LIMIT 1;
    END IF;

    IF default_agency_id IS NULL THEN
        INSERT INTO public.agency (code, name, active, visibility, reg_user_id, date_reg)
        VALUES ('DEFAULT', 'Agence par défaut', TRUE, 'ENABLED', 'SYSTEM_MIGRATION', NOW())
        RETURNING id INTO default_agency_id;
    END IF;

    -- 8.1 Backfill stock_reception & article_stock_lot agency_id + lot_code
    UPDATE public.stock_reception
    SET agency_id = default_agency_id
    WHERE agency_id IS NULL;

    UPDATE public.article_stock_lot
    SET agency_id = default_agency_id
    WHERE agency_id IS NULL;

    UPDATE public.article_stock_lot
    SET lot_code = 'LOT-' || LPAD(id::text, 8, '0')
    WHERE lot_code IS NULL;

    -- 8.2 Backfill warehouse_stock_position for default agency from articles
    INSERT INTO public.warehouse_stock_position (
        agency_id, article_id, on_hand_quantity, reserved_quantity,
        reorder_point, optimal_stock_level, last_restock_date
    )
    SELECT
        default_agency_id,
        a.id,
        GREATEST(COALESCE(a.stock_quantity, 0), 0),
        LEAST(GREATEST(COALESCE(a.reserved_quantity, 0), 0), GREATEST(COALESCE(a.stock_quantity, 0), 0)),
        a.reorder_point,
        a.optimal_stock_level,
        a.last_restock_date
    FROM public.articles a
    ON CONFLICT (agency_id, article_id) DO NOTHING;

    -- Initialize 0-quantity positions for all other active agencies so every agency has catalog coverage
    INSERT INTO public.warehouse_stock_position (
        agency_id, article_id, on_hand_quantity, reserved_quantity,
        reorder_point, optimal_stock_level
    )
    SELECT
        ag.id,
        a.id,
        0,
        0,
        a.reorder_point,
        a.optimal_stock_level
    FROM public.agency ag
    CROSS JOIN public.articles a
    WHERE ag.id <> default_agency_id
    ON CONFLICT (agency_id, article_id) DO NOTHING;

    -- 8.3 Backfill warehouse_stock_ledger_entry from article_history (if not yet migrated)
    IF NOT EXISTS (SELECT 1 FROM public.warehouse_stock_ledger_entry LIMIT 1) THEN
        INSERT INTO public.warehouse_stock_ledger_entry (
            agency_id, article_id, movement_type, quantity_delta,
            on_hand_before, on_hand_after, reserved_before, reserved_after,
            reference_type, reference_id, reference_code, beneficiary, reason,
            performed_by, operation_date, occurred_at
        )
        SELECT
            default_agency_id,
            ah.articles_id,
            COALESCE(ah.operation_type, 'OTHER'),
            COALESCE(ah.final_quantity, 0) - COALESCE(ah.initial_quantity, 0),
            GREATEST(COALESCE(ah.initial_quantity, 0), 0),
            GREATEST(COALESCE(ah.final_quantity, 0), 0),
            0,
            0,
            ah.reference_type,
            ah.reference_id,
            ah.reference_label,
            ah.beneficiary,
            ah.reason,
            ah.operation_user,
            COALESCE(ah.operation_date, ah.occurred_at::date, CURRENT_DATE),
            COALESCE(ah.occurred_at, CURRENT_TIMESTAMP)
        FROM public.article_history ah
        WHERE ah.articles_id IS NOT NULL
        ORDER BY ah.occurred_at ASC, ah.id ASC;
    END IF;

    -- 8.4 Backfill commercial_stock_request from stock_request (CREDIT)
    INSERT INTO public.commercial_stock_request (
        reference, agency_id, commercial_username, activity_type, status,
        request_date, validation_date, delivery_date, accounting_date,
        total_sale_price, total_purchase_price, note,
        legacy_credit_request_id, created_by, created_at, updated_at
    )
    SELECT
        COALESCE(sr.reference, 'REQ-LEGACY-' || sr.id::text),
        COALESCE(sr.agency_id, default_agency_id),
        COALESCE(sr.commercial_username, sr.collector, 'UNKNOWN'),
        'CREDIT',
        COALESCE(sr.status, 'CREATED'),
        COALESCE(sr.request_date, sr.date_reg::date, CURRENT_DATE),
        sr.validation_date,
        sr.delivery_date,
        sr.accounting_date,
        COALESCE(sr.total_credit_sale_price, 0),
        COALESCE(sr.total_purchase_price, 0),
        sr.note,
        sr.id,
        sr.reg_user_id,
        COALESCE(sr.date_reg, CURRENT_TIMESTAMP),
        COALESCE(sr.date_mod, sr.date_reg, CURRENT_TIMESTAMP)
    FROM public.stock_request sr
    WHERE sr.credit_id IS NULL
      AND NOT EXISTS (
          SELECT 1 FROM public.commercial_stock_request csr
          WHERE csr.legacy_credit_request_id = sr.id
             OR csr.reference = COALESCE(sr.reference, 'REQ-LEGACY-' || sr.id::text)
      );

    INSERT INTO public.commercial_stock_request_item (
        request_id, article_id, item_name, quantity_requested,
        quantity_reserved, quantity_delivered, shortage_quantity,
        unit_sale_price, unit_purchase_cost
    )
    SELECT
        csr.id,
        sri.article_id,
        sri.item_name,
        GREATEST(COALESCE(sri.quantity, 1), 1),
        0,
        CASE WHEN csr.status = 'DELIVERED' THEN GREATEST(COALESCE(sri.quantity, 1), 1) ELSE 0 END,
        CASE WHEN csr.status IN ('CREATED', 'VALIDATED') THEN GREATEST(COALESCE(sri.quantity, 1), 1) ELSE 0 END,
        COALESCE(sri.unit_price, 0),
        COALESCE(sri.purchase_price, 0)
    FROM public.stock_request_item sri
    JOIN public.commercial_stock_request csr ON csr.legacy_credit_request_id = sri.stock_request_id
    WHERE sri.article_id IS NOT NULL
      AND NOT EXISTS (
          SELECT 1 FROM public.commercial_stock_request_item csri
          WHERE csri.request_id = csr.id AND csri.article_id = sri.article_id
      );

    -- 8.5 Backfill commercial_stock_request from stock_tontine_request (TONTINE)
    INSERT INTO public.commercial_stock_request (
        reference, agency_id, commercial_username, activity_type, status,
        request_date, validation_date, delivery_date, accounting_date,
        total_sale_price, total_purchase_price, note,
        legacy_tontine_request_id, created_by, created_at, updated_at
    )
    SELECT
        COALESCE(str.reference, 'TRQ-LEGACY-' || str.id::text),
        COALESCE(str.agency_id, default_agency_id),
        COALESCE(str.commercial_username, str.collector, 'UNKNOWN'),
        'TONTINE',
        COALESCE(str.status, 'CREATED'),
        COALESCE(str.request_date, str.date_reg::date, CURRENT_DATE),
        str.validation_date,
        str.delivery_date,
        str.accounting_date,
        COALESCE(str.total_sale_price, 0),
        COALESCE(str.total_purchase_price, 0),
        str.note,
        str.id,
        str.reg_user_id,
        COALESCE(str.date_reg, CURRENT_TIMESTAMP),
        COALESCE(str.date_mod, str.date_reg, CURRENT_TIMESTAMP)
    FROM public.stock_tontine_request str
    WHERE NOT EXISTS (
        SELECT 1 FROM public.commercial_stock_request csr
        WHERE csr.legacy_tontine_request_id = str.id
           OR csr.reference = COALESCE(str.reference, 'TRQ-LEGACY-' || str.id::text)
    );

    INSERT INTO public.commercial_stock_request_item (
        request_id, article_id, item_name, quantity_requested,
        quantity_reserved, quantity_delivered, shortage_quantity,
        unit_sale_price, unit_purchase_cost
    )
    SELECT
        csr.id,
        stri.article_id,
        stri.item_name,
        GREATEST(COALESCE(stri.quantity, 1), 1),
        0,
        CASE WHEN csr.status = 'DELIVERED' THEN GREATEST(COALESCE(stri.quantity, 1), 1) ELSE 0 END,
        CASE WHEN csr.status IN ('CREATED', 'VALIDATED') THEN GREATEST(COALESCE(stri.quantity, 1), 1) ELSE 0 END,
        COALESCE(stri.unit_price, 0),
        COALESCE(stri.purchase_price, 0)
    FROM public.stock_tontine_request_item stri
    JOIN public.commercial_stock_request csr ON csr.legacy_tontine_request_id = stri.stock_tontine_request_id
    WHERE stri.article_id IS NOT NULL
      AND NOT EXISTS (
          SELECT 1 FROM public.commercial_stock_request_item csri
          WHERE csri.request_id = csr.id AND csri.article_id = stri.article_id
      );

    -- 8.6 Backfill commercial_stock_return from stock_return (CREDIT) & stock_tontine_return (TONTINE)
    INSERT INTO public.commercial_stock_return (
        reference, agency_id, commercial_username, activity_type, status,
        return_date, received_date, note,
        legacy_credit_return_id, created_by, created_at, updated_at
    )
    SELECT
         COALESCE(sr.reference, 'RET-CREDIT-' || sr.id::text),
         COALESCE(sr.agency_id, default_agency_id),
         COALESCE(sr.commercial_username, sr.collector, 'UNKNOWN'),
         'CREDIT',
         CASE WHEN sr.status = 'RECEIVED' THEN 'VALIDATED' ELSE COALESCE(sr.status, 'CREATED') END,
         COALESCE(sr.return_date, sr.date_reg::date, CURRENT_DATE),
         sr.received_date,
         sr.note,
         sr.id,
         sr.reg_user_id,
         COALESCE(sr.date_reg, CURRENT_TIMESTAMP),
         COALESCE(sr.date_mod, sr.date_reg, CURRENT_TIMESTAMP)
    FROM public.stock_return sr
    WHERE NOT EXISTS (
        SELECT 1 FROM public.commercial_stock_return csret
        WHERE csret.legacy_credit_return_id = sr.id
    );

    INSERT INTO public.commercial_stock_return_item (
        return_id, article_id, quantity, unit_sale_price
    )
    SELECT
        csret.id,
        sri.article_id,
        GREATEST(COALESCE(sri.quantity, 1), 1),
        COALESCE(sri.unit_price, 0)
    FROM public.stock_return_item sri
    JOIN public.commercial_stock_return csret ON csret.legacy_credit_return_id = sri.stock_return_id
    WHERE sri.article_id IS NOT NULL
      AND NOT EXISTS (
          SELECT 1 FROM public.commercial_stock_return_item csreti
          WHERE csreti.return_id = csret.id AND csreti.article_id = sri.article_id
      );

    INSERT INTO public.commercial_stock_return (
        reference, agency_id, commercial_username, activity_type, status,
        return_date, received_date, received_by, note,
        legacy_tontine_return_id, created_by, created_at, updated_at
