-- Lien entre une demande de sortie tontine et les commandes de livraison qu'elle regroupe.

CREATE TABLE IF NOT EXISTS public.stock_tontine_request_delivery (
    id bigint NOT NULL,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL,
    stock_tontine_request_id bigint NOT NULL,
    tontine_delivery_id bigint NOT NULL,
    CONSTRAINT stock_tontine_request_delivery_pkey PRIMARY KEY (id),
    CONSTRAINT stock_tontine_request_delivery_visibility_check CHECK (
        (visibility)::text = ANY (ARRAY[
            ('ENABLED'::character varying)::text,
            ('DISABLED'::character varying)::text,
            ('DELETED'::character varying)::text
        ])
    ),
    CONSTRAINT fk_stock_tontine_request_delivery_request FOREIGN KEY (stock_tontine_request_id)
        REFERENCES public.stock_tontine_request (id),
    CONSTRAINT fk_stock_tontine_request_delivery_delivery FOREIGN KEY (tontine_delivery_id)
        REFERENCES public.tontine_delivery (id)
);

ALTER TABLE public.stock_tontine_request_delivery ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.stock_tontine_request_delivery_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE INDEX IF NOT EXISTS idx_stock_tontine_request_delivery_delivery_id
    ON public.stock_tontine_request_delivery (tontine_delivery_id);

CREATE INDEX IF NOT EXISTS idx_stock_tontine_request_delivery_request_id
    ON public.stock_tontine_request_delivery (stock_tontine_request_id);

CREATE UNIQUE INDEX IF NOT EXISTS uk_stock_tontine_request_delivery_active
    ON public.stock_tontine_request_delivery (stock_tontine_request_id, tontine_delivery_id)
    WHERE visibility <> 'DELETED';
