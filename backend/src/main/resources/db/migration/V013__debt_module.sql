-- Module dettes : stock commercial (quantité dette), registre unifié, règlements.

ALTER TABLE public.commercial_monthly_stock_item
    ADD COLUMN IF NOT EXISTS quantity_debt integer DEFAULT 0,
    ADD COLUMN IF NOT EXISTS debt_unit_price double precision DEFAULT 0;

UPDATE public.commercial_monthly_stock_item
SET quantity_debt = 0
WHERE quantity_debt IS NULL;

UPDATE public.commercial_monthly_stock_item
SET debt_unit_price = 0
WHERE debt_unit_price IS NULL;

CREATE TABLE IF NOT EXISTS public.debt_document (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL DEFAULT 'ENABLED',
    reference character varying(40) NOT NULL,
    holder_username character varying(100) NOT NULL,
    holder_profile character varying(30) NOT NULL,
    debt_type character varying(40) NOT NULL,
    period_grain character varying(10) NOT NULL,
    period_year integer NOT NULL,
    period_month integer,
    period_day date,
    status character varying(30) NOT NULL,
    gross_amount double precision NOT NULL DEFAULT 0,
    offset_amount double precision NOT NULL DEFAULT 0,
    paid_amount double precision NOT NULL DEFAULT 0,
    remaining_amount double precision NOT NULL DEFAULT 0,
    monthly_stock_id bigint,
    daily_report_id bigint,
    inventory_id bigint,
    created_by character varying(100),
    cancelled_by character varying(100),
    cancelled_at timestamp(6) without time zone,
    cancel_reason character varying(1000),
    CONSTRAINT debt_document_visibility_check CHECK (((visibility)::text = ANY (ARRAY[('ENABLED'::character varying)::text, ('DISABLED'::character varying)::text, ('DELETED'::character varying)::text]))),
    CONSTRAINT debt_document_reference_uk UNIQUE (reference),
    CONSTRAINT fk_debt_document_monthly_stock FOREIGN KEY (monthly_stock_id) REFERENCES public.commercial_monthly_stock(id),
    CONSTRAINT fk_debt_document_daily_report FOREIGN KEY (daily_report_id) REFERENCES public.daily_commercial_report(id),
    CONSTRAINT fk_debt_document_inventory FOREIGN KEY (inventory_id) REFERENCES public.inventory(id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_debt_document_active_period
    ON public.debt_document (holder_username, debt_type, period_grain, period_year, COALESCE(period_month, 0), COALESCE(period_day, DATE '1900-01-01'))
    WHERE status <> 'CANCELLED' AND visibility = 'ENABLED';

CREATE INDEX IF NOT EXISTS idx_debt_document_holder_year
    ON public.debt_document (holder_username, period_year, debt_type);

CREATE INDEX IF NOT EXISTS idx_debt_document_status
    ON public.debt_document (status);

CREATE TABLE IF NOT EXISTS public.debt_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL DEFAULT 'ENABLED',
    debt_document_id bigint NOT NULL,
    article_id bigint,
    stock_item_id bigint,
    inventory_item_id bigint,
    line_code character varying(60),
    label character varying(255),
    quantity integer,
    unit_price double precision DEFAULT 0,
    amount double precision NOT NULL DEFAULT 0,
    price_basis character varying(30),
    sort_order integer DEFAULT 0,
    CONSTRAINT debt_line_visibility_check CHECK (((visibility)::text = ANY (ARRAY[('ENABLED'::character varying)::text, ('DISABLED'::character varying)::text, ('DELETED'::character varying)::text]))),
    CONSTRAINT fk_debt_line_document FOREIGN KEY (debt_document_id) REFERENCES public.debt_document(id) ON DELETE CASCADE,
    CONSTRAINT fk_debt_line_article FOREIGN KEY (article_id) REFERENCES public.articles(id),
    CONSTRAINT fk_debt_line_stock_item FOREIGN KEY (stock_item_id) REFERENCES public.commercial_monthly_stock_item(id),
    CONSTRAINT fk_debt_line_inventory_item FOREIGN KEY (inventory_item_id) REFERENCES public.inventory_item(id)
);

CREATE INDEX IF NOT EXISTS idx_debt_line_document
    ON public.debt_line (debt_document_id);

CREATE TABLE IF NOT EXISTS public.debt_settlement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL DEFAULT 'ENABLED',
    reference character varying(40) NOT NULL,
    settlement_mode character varying(30) NOT NULL,
    amount double precision NOT NULL DEFAULT 0,
    surplus_debt_id bigint,
    note character varying(1000),
    performed_by character varying(100) NOT NULL,
    performed_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT debt_settlement_visibility_check CHECK (((visibility)::text = ANY (ARRAY[('ENABLED'::character varying)::text, ('DISABLED'::character varying)::text, ('DELETED'::character varying)::text]))),
    CONSTRAINT debt_settlement_reference_uk UNIQUE (reference),
    CONSTRAINT fk_debt_settlement_surplus FOREIGN KEY (surplus_debt_id) REFERENCES public.debt_document(id)
);

CREATE TABLE IF NOT EXISTS public.debt_allocation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL DEFAULT 'ENABLED',
    settlement_id bigint NOT NULL,
    debt_document_id bigint NOT NULL,
    amount double precision NOT NULL DEFAULT 0,
    CONSTRAINT debt_allocation_visibility_check CHECK (((visibility)::text = ANY (ARRAY[('ENABLED'::character varying)::text, ('DISABLED'::character varying)::text, ('DELETED'::character varying)::text]))),
    CONSTRAINT fk_debt_allocation_settlement FOREIGN KEY (settlement_id) REFERENCES public.debt_settlement(id) ON DELETE CASCADE,
    CONSTRAINT fk_debt_allocation_document FOREIGN KEY (debt_document_id) REFERENCES public.debt_document(id)
);

CREATE INDEX IF NOT EXISTS idx_debt_allocation_document
    ON public.debt_allocation (debt_document_id);
CREATE INDEX IF NOT EXISTS idx_debt_allocation_settlement
    ON public.debt_allocation (settlement_id);
