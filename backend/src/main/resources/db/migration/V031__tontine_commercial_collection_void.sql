-- Annulation des collectes d'un seul commercial : périmètre du run et copies figées
-- (lignes, compteurs membres, jours de rapport) consultables pour le rapprochement.

ALTER TABLE tontine_collection_reset_run
    ADD COLUMN scope character varying(20) NOT NULL DEFAULT 'SESSION',
    ADD COLUMN target_commercial_username character varying(255);

ALTER TABLE tontine_collection_reset_run
    ADD CONSTRAINT tontine_collection_reset_run_scope_check
        CHECK (scope IN ('SESSION', 'COMMERCIAL'));

CREATE TABLE tontine_collection_reset_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL,
    run_id bigint NOT NULL REFERENCES tontine_collection_reset_run (id),
    collection_id bigint NOT NULL,
    tontine_member_id bigint NOT NULL,
    client_name character varying(500),
    client_code character varying(255),
    quarter character varying(255),
    amount double precision NOT NULL,
    collection_date timestamp(6) without time zone NOT NULL,
    commercial_username character varying(255) NOT NULL,
    reference character varying(255),
    society_share_amount double precision,
    is_delivery_collection boolean,
    contribution_month date,
    recorded_at timestamp(6) without time zone,
    CONSTRAINT tontine_collection_reset_line_visibility_check
        CHECK (visibility IN ('ENABLED', 'DISABLED', 'DELETED'))
);

CREATE INDEX idx_tontine_collection_reset_line_run
    ON tontine_collection_reset_line (run_id);

CREATE TABLE tontine_collection_reset_member (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL,
    run_id bigint NOT NULL REFERENCES tontine_collection_reset_run (id),
    tontine_member_id bigint NOT NULL,
    client_name character varying(500),
    client_code character varying(255),
    total_contribution_before double precision NOT NULL DEFAULT 0,
    society_share_before double precision NOT NULL DEFAULT 0,
    available_contribution_before double precision NOT NULL DEFAULT 0,
    validated_months_before integer NOT NULL DEFAULT 0,
    current_month_days_before integer NOT NULL DEFAULT 0,
    total_contribution_after double precision NOT NULL DEFAULT 0,
    society_share_after double precision NOT NULL DEFAULT 0,
    available_contribution_after double precision NOT NULL DEFAULT 0,
    validated_months_after integer NOT NULL DEFAULT 0,
    current_month_days_after integer NOT NULL DEFAULT 0,
    removed_amount double precision NOT NULL DEFAULT 0,
    kept_amount double precision NOT NULL DEFAULT 0,
    CONSTRAINT tontine_collection_reset_member_visibility_check
        CHECK (visibility IN ('ENABLED', 'DISABLED', 'DELETED'))
);

CREATE INDEX idx_tontine_collection_reset_member_run
    ON tontine_collection_reset_member (run_id);

CREATE TABLE tontine_collection_reset_report_day (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_user_id character varying(50) NOT NULL,
    date_reg timestamp(6) without time zone NOT NULL,
    mod_user_id character varying(50),
    date_mod timestamp(6) without time zone,
    visibility character varying(255) NOT NULL,
    run_id bigint NOT NULL REFERENCES tontine_collection_reset_run (id),
    commercial_username character varying(255) NOT NULL,
    report_date date NOT NULL,
    collections_amount_before double precision NOT NULL DEFAULT 0,
    collections_count_before integer NOT NULL DEFAULT 0,
    catchup_amount_before double precision NOT NULL DEFAULT 0,
    catchup_count_before integer NOT NULL DEFAULT 0,
    amount_to_deposit_before double precision NOT NULL DEFAULT 0,
    collections_amount_after double precision NOT NULL DEFAULT 0,
    collections_count_after integer NOT NULL DEFAULT 0,
    catchup_amount_after double precision NOT NULL DEFAULT 0,
    catchup_count_after integer NOT NULL DEFAULT 0,
    amount_to_deposit_after double precision NOT NULL DEFAULT 0,
    amount_deposited double precision NOT NULL DEFAULT 0,
    tontine_amount_deposited double precision NOT NULL DEFAULT 0,
    CONSTRAINT tontine_collection_reset_report_day_visibility_check
        CHECK (visibility IN ('ENABLED', 'DISABLED', 'DELETED'))
);

CREATE INDEX idx_tontine_collection_reset_report_day_run
    ON tontine_collection_reset_report_day (run_id);
